use YUZTRA\Interfaces\TranslateAdapterInterface;

if (!class_exists('YUZ_Translate_Adapter')) {
    abstract class YUZ_Translate_Adapter {
        /**
         * Tests connectivity to the translation API.
         *
         * @param array $settings API settings (endpoint, API key).
         * @return array Array with 'success' (bool) and 'message' (string).
         */
        abstract public function testConnection(array $settings): bool;

        /**
         * Translates text using the translation API.
         *
         * @param string $text The text to translate.
         * @param string $source_lang The source language code.
         * @param string $target_lang The target language code.
         * @param array $settings API settings (endpoint, API key).
         * @return string|null The translated text, or null on failure.
         */
        abstract public function translate(string $text, string $source_lang, string $target_lang, array $settings): ?string;
    }
}

